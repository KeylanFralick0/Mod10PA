# Module 10: Updated read_penguin_row with FileNotFoundError and raise ValueError
def read_penguin_row(row_number):
    penguin_row = ""

    # open the CSV file and skip the header row with exception handling
    try:
        with open("PalmerPenguins.csv", "r") as penguin_file:
            penguin_file.readline()

            current_row = 1

            # search for the requested data row
            for row in penguin_file:
                if current_row == row_number:
                    penguin_row = row.strip()
                    break

                current_row += 1
    except FileNotFoundError:
        print("Error: PalmerPenguins.csv was not found.")

    # raise ValueError if the requested row does not exist or file was missing
    if not penguin_row:
        raise ValueError(f"Penguin observation {row_number} could not be retrieved.")

    # return the requested row as a string
    return penguin_row


