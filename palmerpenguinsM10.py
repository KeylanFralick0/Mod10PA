# calculate the percentage of penguins in a species group
def calculate_percentage(species_count, total_penguins):
    return species_count / total_penguins * 100


# classify a species group based on its percentage
def classify_species(species_percent):
    if species_percent < 25:
        return "small"
    elif species_percent < 40:
        return "medium"
    else:
        return "large"


# determine the position of a species group
def get_position_description(
        selected_species, largest_species, smallest_species):

    if selected_species == largest_species:
        return "largest"
    elif selected_species == smallest_species:
        return "smallest"
    else:
        return "middle-sized"


# display statistics for one species
def display_species_statistics(
        species, count, percentage, size_category,
        position_description, average_penguins):

    if count > average_penguins:
        average_position = "above"
    else:
        average_position = "below"

    print(f"{species} has {count} observations, "
          f"representing {percentage:.2f}% of the dataset.")

    print(f"{species} is classified as a "
          f"{size_category} species group.")

    print(f"{species} is the {position_description} "
          f"species group.")

    print(f"Its observation count is {average_position} the dataset "
          f"average of {average_penguins:.1f}.")


# display an individual penguin observation
def display_penguin_observation(
        sample_number, species, bill_length, bill_depth,
        body_mass, sex):

    print("Sample Penguin Observation")
    print(f"{'Sample Number:':<20}{sample_number}")
    print(f"{'Species:':<20}{species}")
    print(f"{'Bill length:':<20}{bill_length} mm")
    print(f"{'Bill depth:':<20}{bill_depth} mm")
    print(f"{'Body mass:':<20}{body_mass} g")
    print(f"{'Sex:':<20}{sex}")
    print()


